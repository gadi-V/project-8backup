export const ACADEMIC_UI_UX_ENGINEERING_QUESTIONS = UI_UX_ENGINEERING_QUESTIONS;

/**
 * Stratified onboarding sample:
 * - 1 from Fitts / INVEST / Norman (Q1–3, key A)
 * - 1 from Hick / Nielsen / peeking (Q4–6, key B)
 * - 1 from SUS / walkthrough / WCAG / RTM / Cooper / BDD (Q7–12, keys C–D)
 * then Fisher–Yates shuffle. Fail-closed if any stratum empty.
 */
export function sampleUIUXEngineeringOnboardingQuestions(): AcademicDiagnosticQuestion[] {
  const groupA = UI_UX_ENGINEERING_QUESTIONS.slice(0, 3);
  const groupB = UI_UX_ENGINEERING_QUESTIONS.slice(3, 6);
  const groupC = UI_UX_ENGINEERING_QUESTIONS.slice(6, 12);

  if (groupA.length === 0 || groupB.length === 0 || groupC.length === 0) {
    return [];
  }

  const pickedA = groupA[Math.floor(Math.random() * groupA.length)];
  const pickedB = groupB[Math.floor(Math.random() * groupB.length)];
  const pickedC = groupC[Math.floor(Math.random() * groupC.length)];

  const sampled = [pickedA, pickedB, pickedC].filter(
    (q): q is AcademicDiagnosticQuestion => Boolean(q)
  );

  if (sampled.length !== 3) return [];

  for (let i = sampled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [sampled[i], sampled[j]] = [sampled[j], sampled[i]];
  }
  return sampled;
}
