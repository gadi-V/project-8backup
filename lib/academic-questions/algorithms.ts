export const ACADEMIC_ALGORITHMS_QUESTIONS = ALGORITHMS_QUESTIONS;

/**
 * Stratified onboarding sample:
 * - 1 from MST / shortest paths / LCS (Q1–3)
 * - 1 from flow / Huffman / BFPRT (Q4–6)
 * - 1 from SCC / NP / approximation / matching / scheduling / duality (Q7–12)
 * then Fisher–Yates shuffle. Fail-closed if any stratum empty.
 */
export function sampleAlgorithmsOnboardingQuestions(): AcademicDiagnosticQuestion[] {
  const groupBasics = ALGORITHMS_QUESTIONS.slice(0, 3);
  const groupMid = ALGORITHMS_QUESTIONS.slice(3, 6);
  const groupAdvanced = ALGORITHMS_QUESTIONS.slice(6, 12);

  if (
    groupBasics.length === 0 ||
    groupMid.length === 0 ||
    groupAdvanced.length === 0
  ) {
    return [];
  }

  const pickedA =
    groupBasics[Math.floor(Math.random() * groupBasics.length)];
  const pickedB = groupMid[Math.floor(Math.random() * groupMid.length)];
  const pickedC =
    groupAdvanced[Math.floor(Math.random() * groupAdvanced.length)];

  const sampled = [pickedA, pickedB, pickedC].filter(
    (q): q is AcademicDiagnosticQuestion => Boolean(q)
  );

  if (sampled.length !== 3) return [];

  for (let i = sampled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [sampled[i], sampled[j]] = [sampled[j], sampled[i]];
  }

  return sampled;
}
